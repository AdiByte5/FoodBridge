#!/usr/bin/env bash
# Creates two double-clickable launchers on the Desktop:
#   FoodBridge.command       -> starts the database, API and web app, then opens the site
#   Stop FoodBridge.command  -> shuts everything down again
#
# macOS blocks app bundles from reading a project inside ~/Documents without a
# permission prompt, so these are Terminal launchers (.command) — Terminal asks
# for Documents access once, then every double-click just works.
#
# Re-run this script any time (e.g. after moving the project folder) to refresh them.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DESKTOP="$HOME/Desktop"
RUNDIR="$HOME/.foodbridge/run"
ICON_PNG="$ROOT/docs/branding/foodbridge-icon.png"
mkdir -p "$RUNDIR"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

write_launcher() {
  local file="$1" title="$2" body="$3"
  cat > "$file" <<LAUNCHER
#!/bin/zsh
# $title — generated by FoodBridge/scripts/make-desktop-launcher.sh
export PATH="/opt/homebrew/bin:/opt/homebrew/opt/openjdk@21/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
cd "$ROOT" || exit 1

echo "── FoodBridge ──────────────────────────────────────────────"
LOG="\$HOME/.foodbridge/run/launcher.log"
{
  echo "[\$(date '+%Y-%m-%d %H:%M:%S')] launcher started"
$body
  echo "[\$(date '+%Y-%m-%d %H:%M:%S')] launcher finished"
} 2>&1 | tee -a "\$LOG"
LAUNCHER
  chmod +x "$file"
}

write_launcher "$DESKTOP/FoodBridge.command" "start FoodBridge" '
if ./scripts/start-all.sh; then
  open "http://localhost:5173"
  echo
  echo "✓ FoodBridge is running — the site is open in your browser."
  echo "  You can close this window; the app keeps running."
else
  echo
  echo "✗ Something went wrong. Details: ~/.foodbridge/run/backend.log"
  echo "  Press any key to close."
  read -k 1
fi'

write_launcher "$DESKTOP/Stop FoodBridge.command" "stop FoodBridge" '
./scripts/stop-all.sh
echo
echo "✓ FoodBridge stopped. You can close this window."
sleep 2'

# ---------------------------------------------------------------- icons
# Give the .command files the FoodBridge icon: sips writes the icon into a copy
# of the PNG's resource fork, DeRez extracts it, Rez appends it to the script and
# SetFile marks the file as having a custom icon (the standard macOS recipe).
if [ -f "$ICON_PNG" ] && command -v Rez >/dev/null && command -v DeRez >/dev/null && command -v SetFile >/dev/null; then
  cp "$ICON_PNG" "$TMP/icon-source.png"
  if sips -i "$TMP/icon-source.png" >/dev/null 2>&1 &&
     DeRez -only icns "$TMP/icon-source.png" > "$TMP/icon.rsrc" 2>/dev/null &&
     [ -s "$TMP/icon.rsrc" ]; then
    for file in "$DESKTOP/FoodBridge.command" "$DESKTOP/Stop FoodBridge.command"; do
      if Rez -append "$TMP/icon.rsrc" -o "$file" >/dev/null 2>&1; then
        SetFile -a C "$file" >/dev/null 2>&1 || true
      fi
    done
  fi
fi

echo "✓ FoodBridge.command and Stop FoodBridge.command are on your Desktop"
echo "  (they point at $ROOT — re-run this script if the project moves)"
echo
echo "  First double-click: macOS may ask to let Terminal access your Documents"
echo "  folder — click Allow once and it never asks again."
